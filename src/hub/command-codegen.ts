// `pnpm gen:wire` (scripts/gen-desktop-wire.ts) and its drift test (src/wire.test.ts) both derive
// from here: the hub command index (src/hub/commands/index.ts) and the desktop copy's `Commands` /
// `COMMAND_NAMES`, from the per-feature modules in src/hub/commands/. Pure text in, text out.
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';

export interface CommandModuleInfo {
  /** File stem, e.g. `needs-you`. */
  file: string;
  /** Local binding for the module's handlers, e.g. `needsYou`. */
  binding: string;
  /** The module's wire interface, e.g. `NeedsYouCommands`. */
  iface: string;
  /** The interface's members, doc comments included, as written. */
  members: string;
  names: string[];
}

const camel = (stem: string): string => stem.replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

/** Every feature module in `commandsDir`, sorted by file name (so independent additions land apart). */
export function readCommandModules(commandsDir: string): CommandModuleInfo[] {
  return readdirSync(commandsDir)
    .filter((f) => f.endsWith('.ts') && f !== 'index.ts' && !f.endsWith('.test.ts'))
    .sort()
    .map((f) => {
      const file = f.slice(0, -3);
      const src = readFileSync(join(commandsDir, f), 'utf8');
      const m = /^export interface (\w+Commands) \{\n([\s\S]*?)\n\}\n/m.exec(src);
      if (m === null) throw new Error(`${f}: no \`export interface <Feature>Commands { ... }\` found`);
      const members = m[2] ?? '';
      const names = [...members.matchAll(/^  ([a-z][a-z0-9_]*): /gm)].map((x) => x[1] as string);
      return { file, binding: camel(file), iface: m[1] as string, members, names };
    });
}

const allNames = (mods: CommandModuleInfo[]): string[] => mods.flatMap((m) => m.names).sort();

const NAMES_DOC = `/** Every command name, derived from the modules in src/hub/commands/. TYPE-CHECKED against \`Commands\`:
 * the \`satisfies\` rejects a name not in \`Commands\`, and \`_Exhaustive\` rejects a missing one. */`;

function namesBlock(mods: CommandModuleInfo[]): string {
  return `${NAMES_DOC}
export const COMMAND_NAMES = [
${allNames(mods).map((n) => `  '${n}',`).join('\n')}
] as const satisfies readonly (keyof Commands)[];
type _Exhaustive = keyof Commands extends (typeof COMMAND_NAMES)[number]
  ? true
  : ['missing from COMMAND_NAMES', Exclude<keyof Commands, (typeof COMMAND_NAMES)[number]>];
const _exhaustive: _Exhaustive = true;
void _exhaustive;
`;
}

/** src/hub/commands/index.ts: the merged `Commands`, `COMMAND_NAMES`, and the dispatch/audit lookups. */
export function commandIndexSource(mods: CommandModuleInfo[]): string {
  return `// GENERATED by pnpm gen:wire from the modules in this directory — do not edit.
${mods.map((m) => `import { commands as ${m.binding}, type ${m.iface} } from './${m.file}.js';`).join('\n')}
import type { AuditSpec, CommandHandler } from '../command-kit.js';

/** Shared command catalogue for the Tauri, hub and mock adapters: the union of every module's contract. */
export interface Commands extends
${mods.map((m) => `  ${m.iface}`).join(',\n')} {}

${namesBlock(mods)}
/** The dispatch table \`dispatchRpc\` looks a command up in. */
export const HUB_COMMANDS: { readonly [K in keyof Commands]: CommandHandler } = {
${mods.map((m) => `  ...${m.binding}.handlers,`).join('\n')}
};

/** Audited commands: the action each logs, and the target/detail it names (never a value). */
export const HUB_AUDITED: { readonly [K in keyof Commands]?: AuditSpec } = {
${mods.map((m) => `  ...${m.binding}.audit,`).join('\n')}
};
`;
}

/** Appended to the desktop copy of wire.ts (which cannot import hub code): the same \`Commands\` and \`COMMAND_NAMES\`, inlined. */
export function desktopCommandsSource(mods: CommandModuleInfo[]): string {
  return `
/**
 * Shared command catalogue for the Tauri, hub and mock adapters: the union of the hub command
 * modules (src/hub/commands/), inlined here by \`pnpm gen:wire\`.
 */
export interface Commands {
${mods.map((m) => m.members).join('\n')}
}

${namesBlock(mods)}`;
}
